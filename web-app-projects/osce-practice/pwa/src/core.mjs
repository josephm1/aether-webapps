export function sections(markdown) {
  let heading = 'Introduction', body = [], result = [];
  const flush = () => {
    const text = body.join('\n').trim();
    if (text) result.push({id:`S${result.length+1}`, heading, text});
    body = [];
  };
  for (const line of markdown.split(/\r?\n/)) {
    const match = /^(#{1,6})\s+(.+)$/.exec(line);
    if (match) {flush(); heading = match[2].replace(/\*/g,'').trim();}
    else body.push(line);
  }
  flush();
  return result;
}


export function questionCount(value = 12) {
  if (!Number.isInteger(value) || value < 1 || value > 100) throw new Error('Choose 1–100 questions.');
  return value;
}

export function parseResponse(text, source, answered, total) {
  const invalid=()=>new Error('The examiner response must use Feedback, Case update, Question and Evidence headings in that order. Retry this question.');
  if(typeof text!=='string' || new TextEncoder().encode(text).length>64000) throw invalid();
  const headings=['## Feedback','## Case update','## Question','## Evidence'];
  const blocks=headings.map(()=>[]);let current=-1;
  for(const line of text.replaceAll('\r\n','\n').trim().split('\n')) {
    const heading=line.trim();
    if(heading.startsWith('```') || heading.startsWith('~~~')) throw invalid();
    if(heading.startsWith('#')) {
      if(heading!==headings[current+1]) throw invalid();
      current++;
    } else {
      if(current<0) throw invalid();
      blocks[current].push(line);
    }
  }
  if(current!==headings.length-1) throw invalid();
  const [feedbackText,caseUpdate,question,evidence]=blocks.map(lines=>lines.join('\n').trim());
  const feedback=feedbackText ? (feedbackText.startsWith('- ') ? feedbackText.slice(2).split('\n- ') : [feedbackText]) : [];
  if(feedbackText.length>12000 || feedback.some(x=>!x.trim() || x.length>4000) || (answered>0 ? !feedback.length : feedback.length)) throw new Error(feedbackText.length>12000 || feedback.some(x=>x.length>4000) ? 'The examiner feedback was too long. Retry this question.' : answered>0 ? 'The examiner did not give feedback on your answer. Retry this question.' : 'The examiner gave feedback before an answer was submitted. Retry this question.');
  if(caseUpdate.length>12000 || question.length>12000) throw new Error('Invalid examiner text. Retry this question.');
  if(answered===total ? question || caseUpdate : !question) throw new Error('The examiner did not respect the question count.');
  const citations=[], references=evidence.split('\n').filter(line=>line.trim());
  if(!references.length || references.length>8) throw new Error('The examiner did not supply source references.');
  for(const line of references) {
    const end=line.indexOf(']');
    const id=line.startsWith('[') ? line.slice(1,end) : line.trim();
    const section=source.sections.find(s=>s.id===id);
    if(!section) throw new Error('The examiner referenced an unknown source section. Retry this question.');
    // Display the saved source, never quotation text generated by the model.
    if(!citations.some(c=>c.section===id)) citations.push({section:id});
  }
  return {feedback,caseUpdate,question,citations};
}

